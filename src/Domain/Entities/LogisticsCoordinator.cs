namespace Smart_Routes.Domain.Entities;

/// <summary>
/// COORDINADOR_LOGISTICO (subtype of USUARIO). Enters orders, defines balance criteria,
/// generates routes and resolves rescheduling requests.
/// </summary>
public class LogisticsCoordinator : BaseUserProfile
{
    /// <summary>Specialty (especialidad).</summary>
    public string Specialty { get; set; } = string.Empty;

    /// <summary>AUTORIZADO_EN: centers where the coordinator can enter orders and generate routes.</summary>
    public IList<CoordinatorCenter> AuthorizedCenters { get; private set; } = new List<CoordinatorCenter>();

    /// <summary>INGRESA: orders entered by this coordinator (id_coord_ingreso).</summary>
    public IList<Order> EnteredOrders { get; private set; } = new List<Order>();

    /// <summary>GENERA: routes generated by this coordinator (id_coord_generador).</summary>
    public IList<Route> GeneratedRoutes { get; private set; } = new List<Route>();

    /// <summary>DEFINE: balance criteria authored by this coordinator (id_coord_autor).</summary>
    public IList<BalanceCriterion> AuthoredCriteria { get; private set; } = new List<BalanceCriterion>();

    /// <summary>RESUELVE: rescheduling requests assigned to this coordinator (id_coord_resolutor).</summary>
    public IList<Rescheduling> AssignedReschedulings { get; private set; } = new List<Rescheduling>();
}
